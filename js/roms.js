/* =========================================
   CREATE ROM CARDS
========================================= */

romOrder.forEach((romKey, index) => {

    const rom = roms[romKey];

    const card =
        document.createElement("button");

    card.className = "rom-card";

    card.type = "button";

    card.dataset.rom = romKey;


    /*
       Highlight OS in red
       Example:
       LUNARISOS → LUNARIS + OS
    */

let displayName = formatRomName(rom.name);

    card.innerHTML = `


        <h3>
            ${displayName}
        </h3>

        <small>
            ${rom.type}
        </small>

        <span class="rom-arrow">
            ↗
        </span>

    `;


    card.addEventListener(
        "click",
        () => selectRom(romKey)
    );


    romGrid.appendChild(card);

});



/* =========================================
   SELECT ROM
========================================= */

function selectRom(romKey) {

    const rom = roms[romKey];

    if (!rom) return;


    /*
       Change featured content
    */

    featuredName.innerHTML =
        formatRomName(rom.name);

    featuredType.textContent =
        rom.type;

    featuredDescription.textContent =
        rom.description;


    /*
       Change ROM logo
    */

    featuredLogo.src =
        rom.logo;

    featuredLogo.alt =
        rom.name + " logo";


    /*
       Change download links
    */

    vanillaPixelDrain.href =
        rom.vanilla.pixeldrain;

    vanillaGoFile.href =
        rom.vanilla.gofile;

    gappsPixelDrain.href =
        rom.gapps.pixeldrain;

    gappsGoFile.href =
        rom.gapps.gofile;


    /*
       Active card
    */

    document
        .querySelectorAll(".rom-card")
        .forEach(card => {

            card.classList.toggle(
                "active",
                card.dataset.rom === romKey
            );

        });


    /*
       Small visual refresh
       WITHOUT reloading page
    */

    const featured =
        document.getElementById("featuredRom");

    featured.classList.remove("rom-changing");

    void featured.offsetWidth;

    featured.classList.add("rom-changing");

}



/* =========================================
   FORMAT ROM NAME
========================================= */

function formatRomName(name) {

    const suffixes = {
        "LINEAGEOS": ["LINEAGE", "OS"],
        "LUNARISOS": ["LUNARIS", "OS"],
        "MISTOS": ["MIST", "OS"],
        "VOLATGEOS": ["VOLATGE", "OS"],
        "PIXELIFYOS": ["PIXELIFY", "OS"],
        "RISINGOS": ["RISING", "OS"],
        "DERPFEST": ["DERP", "FEST"],
        "AXIONOS": ["AXION", "OS"],
        "LUMINEDROID": ["LUMINE", "DROID"],
        "NYX ROM": ["NYX", "ROM"],
        "SHINKAI PR": ["SHINKAI", "PR"],
        "INFINITYX": ["INFINITY", "X"],
        "PIXELOS": ["PIXEL", "OS"]
    };


    if (suffixes[name]) {

        const [main, suffix] = suffixes[name];

        return `
            ${main}<span>${suffix}</span>
        `;
    }


    return name;
}

